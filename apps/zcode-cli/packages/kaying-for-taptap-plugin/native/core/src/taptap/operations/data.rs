/// Prepare a data operation — validate args and return a plan.
pub fn prepare_data(request: &OperationRequest) -> Result<OperationPlan, PrepareError> {
    let effects = match request.operation_id.as_str() {
        "data.get_locale" => vec![Effect::ReadProject],
        "data.set_locale"
        | "data.create_save_schema"
        | "data.save_game"
        | "data.load_game"
        | "data.clear_save"
        | "data.create_i18n"
        | "data.create_config"
        | "data.validate"
        | "data.migrate" => {
            vec![Effect::ReadProject, Effect::WriteProject]
        }
        _ => vec![Effect::ReadProject],
    };
    make_plan(request, &PLAN_COUNTER, effects, "data-effects")
}
