/// Handle `debug.get_frame_metrics` — generate metrics reader and return any
/// persisted frame metrics from `.project/diagnostics/frame-metrics.json`.
pub fn debug_get_frame_metrics(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();

    // Generate reader function in profiler.lua.
    let marker = "-- @debug.get_frame_metrics";
    let snippet = format!(
        "\n{marker}\n-- Read frame metrics persisted by the runtime.\nfunction Profiler.get_frame_metrics()\n    return Profiler.samples\nend\n"
    );
    let appended = append_to_profiler(&root, &snippet, marker)?;
    let path = profiler_lua(&root);

    // Read persisted metrics if the runtime has dumped them.
    let metrics_path = diagnostics_dir(&root).join("frame-metrics.json");
    let persisted = read_json_file_opt(&metrics_path).map_err(ExecuteError::Io)?;

    info!(
        appended,
        has_persisted = persisted.is_some(),
        "Frame metrics reader generated"
    );

    Ok(ok_result(
        request,
        json!({
            "generated": true,
            "appended": appended,
            "path": path.to_string_lossy(),
            "persisted_metrics_path": metrics_path.to_string_lossy(),
            "has_persisted_metrics": persisted.is_some(),
            "metrics": persisted,
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

