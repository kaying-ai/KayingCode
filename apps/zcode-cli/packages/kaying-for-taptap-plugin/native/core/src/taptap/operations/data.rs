/// Handle `data.load_game` — generate load function inside `scripts/data/save.lua`.
pub fn data_load_game(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let slot = str_arg(request, "slot", "default");

    let path = data_dir(&root).join("save.lua");
    let snippet = format!(
        "\nfunction Save.read(slot)\n  slot = slot or \"{slot}\"\n  -- TODO: bridge to engine storage API; validate via Schema.validate\n  return nil\nend\n"
    );

    if !path.exists() {
        let body = format!(
            "-- save.lua — Save game persistence (slot={slot})\nlocal Save = {{}}\n{snippet}\nreturn Save\n"
        );
        ensure_parent(&path)?;
        std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    } else {
        let mut content = std::fs::read_to_string(&path).map_err(ExecuteError::Io)?;
        if !content.contains("function Save.read") {
            content.push_str(&snippet);
            std::fs::write(&path, &content).map_err(ExecuteError::Io)?;
        }
    }

    info!(path = %path.to_string_lossy(), "Load function ensured");
    Ok(ok_result(
        request,
        json!({
            "ensured": true,
            "path": path.to_string_lossy(),
            "slot": slot,
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

