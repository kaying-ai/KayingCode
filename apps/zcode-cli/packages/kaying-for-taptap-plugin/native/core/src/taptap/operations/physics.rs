//! TapTap physics operations — rigidbodies, colliders, joints, gravity.
//!
//! Physics materials live under `.project/physics-materials/`. Generated
//! query helpers are appended to `scripts/systems/physics.lua`. Scene-level
//! changes (rigidbody/collider/joint components) are recorded in
//! `.project/physics-overrides.json` for runtime composition.

use crate::model::{
    Effect, ExecuteError, OperationPlan, OperationRequest, OperationResult, PrepareError,
};
use crate::taptap::operations::helpers::{
    fail_result, get_project_root, make_plan, ok_result, read_json_file_opt, required_str_arg,
    str_arg, write_json_file,
};
use serde_json::json;
use std::path::{Path, PathBuf};
use std::sync::atomic::AtomicU64;
use std::time::Instant;
use tracing::info;

static PLAN_COUNTER: AtomicU64 = AtomicU64::new(0);

fn physics_dir(root: &Path) -> PathBuf {
    root.join(".project").join("physics-materials")
}

fn physics_lua(root: &Path) -> PathBuf {
    root.join("scripts").join("systems").join("physics.lua")
}

fn physics_overrides(root: &Path) -> PathBuf {
    root.join(".project").join("physics-overrides.json")
}

fn project_json(root: &Path) -> PathBuf {
    root.join(".project").join("project.json")
}

fn ensure_parent(path: &Path) -> Result<(), ExecuteError> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(ExecuteError::Io)?;
    }
    Ok(())
}

fn read_overrides(root: &Path) -> serde_json::Value {
    read_json_file_opt(&physics_overrides(root))
        .ok()
        .flatten()
        .unwrap_or(json!({"bodies": [], "colliders": [], "joints": []}))
}

fn write_overrides(root: &Path, value: &serde_json::Value) -> Result<(), ExecuteError> {
    write_json_file(&physics_overrides(root), value).map_err(ExecuteError::Io)
}

fn append_to_overrides(
    root: &Path,
    field: &str,
    entry: serde_json::Value,
) -> Result<(), ExecuteError> {
    let mut overrides = read_overrides(root);
    let arr = overrides
        .as_object_mut()
        .and_then(|o| o.entry(field).or_insert_with(|| json!([])).as_array_mut());
    if let Some(arr) = arr {
        arr.push(entry);
    }
    write_overrides(root, &overrides)
}

