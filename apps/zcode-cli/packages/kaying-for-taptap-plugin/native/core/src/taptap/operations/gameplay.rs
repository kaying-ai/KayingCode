/// Prepare a gameplay operation.
pub fn prepare_gameplay(request: &OperationRequest) -> Result<OperationPlan, PrepareError> {
    let effects = match request.operation_id.as_str() {
        "gameplay.validate" => vec![Effect::ReadProject],
        _ => vec![Effect::ReadProject, Effect::WriteProject],
    };
    make_plan(request, &PLAN_COUNTER, effects, "gameplay-effects")
}
