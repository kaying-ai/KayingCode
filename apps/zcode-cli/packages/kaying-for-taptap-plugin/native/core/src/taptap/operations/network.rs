/// Handle `network.set_replication` — generate replication config.
pub fn network_set_replication(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let object = required_str_arg(request, "object")?;
    let mode = str_arg(request, "mode", "server_authoritative");
    let path = network_config(&root);
    let body = format!(
        "-- network_config.lua — Replication configuration\n-- Auto-generated by network.set_replication.\n\nreturn {{\n  objects = {{\n    [\"{object}\"] = {{ mode = \"{mode}\" }},\n  }},\n}}\n"
    );
    ensure_parent(&path)?;
    // Merge with existing config if present.
    let final_body = if path.exists() {
        let mut content = std::fs::read_to_string(&path).map_err(ExecuteError::Io)?;
        // Replace return { ... } with the merged version (simple append of the new object entry).
        let insert = format!("    [\"{object}\"] = {{ mode = \"{mode}\" }},\n");
        if let Some(idx) = content.find("objects = {") {
            let after = idx + "objects = {".len();
            content.insert_str(after, &insert);
            content
        } else {
            body
        }
    } else {
        body
    };
    std::fs::write(&path, &final_body).map_err(ExecuteError::Io)?;
    info!(object = %object, mode = %mode, "Replication config written");
    Ok(ok_result(
        request,
        json!({"written": true, "object": object, "mode": mode, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

