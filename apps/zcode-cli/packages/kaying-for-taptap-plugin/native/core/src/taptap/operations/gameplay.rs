/// Handle `gameplay.create_spawn_table` — write `scripts/data/spawn_table.lua`.
pub fn gameplay_create_spawn_table(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = str_arg(request, "name", "spawn_table");
    let entries = request
        .arguments
        .get("entries")
        .cloned()
        .unwrap_or(json!([]));
    let entries_lua = entries
        .as_array()
        .map(|arr| {
            arr.iter()
                .map(|e| {
                    let enemy = e.get("enemy").and_then(|v| v.as_str()).unwrap_or("");
                    let weight = e.get("weight").and_then(|v| v.as_f64()).unwrap_or(1.0);
                    let count = e.get("count").and_then(|v| v.as_u64()).unwrap_or(1);
                    format!("  {{ enemy = \"{enemy}\", weight = {weight}, count = {count} }}")
                })
                .collect::<Vec<_>>()
                .join(",\n")
        })
        .unwrap_or_default();
    let body = format!(
        "-- spawn_table.lua — Spawn table '{name}'\n-- Auto-generated by gameplay.create_spawn_table.\n\nreturn {{\n{entries_lua}\n}}\n"
    );
    let path = data_dir(&root).join(format!("{name}.lua"));
    ensure_parent(&path)?;
    std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    info!(name = %name, "Spawn table created");
    Ok(ok_result(
        request,
        json!({"created": true, "name": name, "entries": entries.as_array().map(|a| a.len()).unwrap_or(0), "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

