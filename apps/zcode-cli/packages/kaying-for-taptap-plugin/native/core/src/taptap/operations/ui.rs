/// Handle `ui.create_element` — append an element factory to a UI module.
pub fn ui_create_element(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let module = required_str_arg(request, "module")?;
    let element_name = required_str_arg(request, "element_name")?;
    let kind = str_arg(request, "kind", "container");
    let pascal = pascal(&element_name);

    let path = ui_dir(&root).join(format!("{module}.lua"));
    let snippet = format!(
        "\nfunction M.create{pascal}(x, y, w, h)\n  return {{ type = \"{kind}\", name = \"{element_name}\", x = x, y = y, w = w, h = h }}\nend\n"
    );

    if !path.exists() {
        let body = format!("-- {module}.lua\nlocal M = {{}}\n{snippet}\nreturn M\n");
        ensure_parent(&path)?;
        std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    } else {
        let mut content = std::fs::read_to_string(&path).map_err(ExecuteError::Io)?;
        let func_name = format!("M.create{pascal}");
        if !content.contains(&func_name) {
            content.push_str(&snippet);
            std::fs::write(&path, &content).map_err(ExecuteError::Io)?;
        } else {
            return Ok(fail_result(
                request,
                json!({"error": format!("Element '{element_name}' already exists in {module}")}),
                started.elapsed().as_millis() as u64,
            ));
        }
    }
    info!(module = %module, element = %element_name, kind = %kind, "Element added");
    Ok(ok_result(
        request,
        json!({"added": true, "module": module, "element_name": element_name, "kind": kind, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

