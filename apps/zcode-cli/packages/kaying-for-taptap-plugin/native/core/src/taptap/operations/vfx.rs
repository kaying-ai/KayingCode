/// Prepare a VFX operation.
pub fn prepare_vfx(request: &OperationRequest) -> Result<OperationPlan, PrepareError> {
    let effects = vec![Effect::ReadProject, Effect::WriteProject];
    let _ = request.operation_id.as_str();
    make_plan(request, &PLAN_COUNTER, effects, "vfx-effects")
}
