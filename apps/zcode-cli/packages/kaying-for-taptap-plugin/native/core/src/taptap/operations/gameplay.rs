/// Handle `gameplay.create_state_machine` — write `scripts/gameplay/state_machine.lua`.
pub fn gameplay_create_state_machine(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = str_arg(request, "name", "state_machine");
    let path = gameplay_dir(&root).join(format!("{name}.lua"));
    if path.exists() {
        return Ok(fail_result(
            request,
            json!({"error": format!("State machine '{name}' already exists")}),
            started.elapsed().as_millis() as u64,
        ));
    }
    let body = "-- state_machine.lua — Gameplay state machine\n-- Auto-generated by gameplay.create_state_machine.\n\nlocal SM = {}\nSM.__index = SM\n\nfunction SM.new()\n  local self = setmetatable({}, SM)\n  self.states = {}\n  self.transitions = {}\n  self.current = nil\n  return self\nend\n\nfunction SM:addState(name, onEnter, onExit, onUpdate)\n  self.states[name] = { onEnter = onEnter, onExit = onExit, onUpdate = onUpdate }\n  if self.current == nil then self.current = name end\nend\n\nfunction SM:addTransition(from, to, condition)\n  table.insert(self.transitions, { from = from, to = to, condition = condition })\nend\n\nfunction SM:tick(...)\n  if self.current and self.states[self.current] and self.states[self.current].onUpdate then\n    self.states[self.current].onUpdate(...)\n  end\n  for _, t in ipairs(self.transitions) do\n    if t.from == self.current and (t.condition == nil or t.condition()) then\n      if self.states[self.current] and self.states[self.current].onExit then\n        self.states[self.current].onExit()\n      end\n      self.current = t.to\n      if self.states[self.current] and self.states[self.current].onEnter then\n        self.states[self.current].onEnter()\n      end\n      break\n    end\n  end\nend\n\nreturn SM\n";
    ensure_parent(&path)?;
    std::fs::write(&path, body).map_err(ExecuteError::Io)?;
    info!(name = %name, "State machine created");
    Ok(ok_result(
        request,
        json!({"created": true, "name": name, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

/// Handle `gameplay.add_state` — register a state on an existing SM (recorded in manifest).
pub fn gameplay_add_state(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let sm_name = str_arg(request, "name", "state_machine");
    let state_name = required_str_arg(request, "state_name")?;
    let path = gameplay_dir(&root).join(format!("{sm_name}.lua"));
    if !path.exists() {
        return Ok(fail_result(
            request,
            json!({"error": format!("State machine '{sm_name}' not found")}),
            started.elapsed().as_millis() as u64,
        ));
    }
    let manifest_path = gameplay_dir(&root).join(format!("{sm_name}.states.json"));
    let mut manifest = read_json_file_opt(&manifest_path)
        .map_err(ExecuteError::Io)?
        .unwrap_or(json!({"states": [], "transitions": []}));
    let states = manifest.as_object_mut().and_then(|o| {
        o.entry("states")
            .or_insert_with(|| json!([]))
            .as_array_mut()
    });
    if let Some(states) = states {
        let exists = states
            .iter()
            .any(|s| s.get("name").and_then(|v| v.as_str()) == Some(&state_name));
        if !exists {
            states.push(json!({"name": state_name}));
        }
    }
    write_json_file(&manifest_path, &manifest).map_err(ExecuteError::Io)?;
    info!(sm = %sm_name, state = %state_name, "State added");
    Ok(ok_result(
        request,
        json!({"added": true, "state_machine": sm_name, "state": state_name, "manifest": manifest_path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

/// Handle `gameplay.add_transition` — record a transition in SM manifest.
pub fn gameplay_add_transition(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let sm_name = str_arg(request, "name", "state_machine");
    let from = required_str_arg(request, "from")?;
    let to = required_str_arg(request, "to")?;
    let manifest_path = gameplay_dir(&root).join(format!("{sm_name}.states.json"));
    let mut manifest = read_json_file_opt(&manifest_path)
        .map_err(ExecuteError::Io)?
        .unwrap_or(json!({"states": [], "transitions": []}));
    let transitions = manifest.as_object_mut().and_then(|o| {
        o.entry("transitions")
            .or_insert_with(|| json!([]))
            .as_array_mut()
    });
    if let Some(transitions) = transitions {
        transitions.push(json!({"from": from, "to": to}));
    }
    write_json_file(&manifest_path, &manifest).map_err(ExecuteError::Io)?;
    info!(sm = %sm_name, from = %from, to = %to, "Transition added");
    Ok(ok_result(
        request,
        json!({"added": true, "state_machine": sm_name, "from": from, "to": to, "manifest": manifest_path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

