/// Handle `data.create_i18n` — write `scripts/data/i18n/<locale>.lua`.
pub fn data_create_i18n(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let locale = required_str_arg(request, "locale")?;
    let table = request.arguments.get("table").cloned().unwrap_or(json!({}));
    let entries_lua = table
        .as_object()
        .map(|o| {
            o.iter()
                .map(|(k, v)| {
                    let val = v.as_str().unwrap_or("");
                    format!("  [\"{k}\"] = \"{val}\"")
                })
                .collect::<Vec<_>>()
                .join(",\n")
        })
        .unwrap_or_default();

    let body = format!(
        "-- i18n/{locale}.lua — Localization table\n-- Auto-generated by data.create_i18n.\n\nreturn {{\n{entries_lua}\n}}\n"
    );

    let path = data_dir(&root).join("i18n").join(format!("{locale}.lua"));
    ensure_parent(&path)?;
    std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    info!(locale = %locale, path = %path.to_string_lossy(), "i18n table created");
    Ok(ok_result(
        request,
        json!({
            "created": true,
            "locale": locale,
            "path": path.to_string_lossy(),
            "entries": table.as_object().map(|o| o.len()).unwrap_or(0),
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

