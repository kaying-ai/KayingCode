import { homedir } from "node:os";
import { delimiter, join } from "node:path";

/**
 * Agent 可用的 kayingcode CLI 入口（shim）路径与脚本生成规则。
 * CLI 在数据目录生成 shim，Bash/tool 子进程把它前置到 PATH；
 * 规则见 apps/zcode-cli/packages/cli/spec/agent-cli-shim.md。
 */

export const AGENT_CLI_SHIM_COMMAND = "kayingcode";

/** 与 Host `getDataBaseDir()` 同规则：KAYINGCODE_DATA_BASE_DIR 优先，空值回落 HOME。 */
export function resolveAgentCliShimDir(env: NodeJS.ProcessEnv = process.env): string {
  const baseDir =
    env.KAYINGCODE_DATA_BASE_DIR?.trim() ||
    env.HOME?.trim() ||
    env.USERPROFILE?.trim() ||
    homedir();
  return join(baseDir, ".kayingcode", "bin");
}

export function resolveAgentCliShimPath(
  env: NodeJS.ProcessEnv = process.env,
  platform: NodeJS.Platform = process.platform,
): string {
  const directory = resolveAgentCliShimDir(env);
  return platform === "win32"
    ? join(directory, `${AGENT_CLI_SHIM_COMMAND}.cmd`)
    : join(directory, AGENT_CLI_SHIM_COMMAND);
}

const PATH_DELIMITER_BY_PLATFORM: Partial<Record<NodeJS.Platform, string>> = {
  win32: ";",
};

function pathDelimiter(platform: NodeJS.Platform): string {
  return PATH_DELIMITER_BY_PLATFORM[platform] ?? delimiter;
}

/**
 * 把 shim 目录前置到 PATH；已存在时不重复，也不改写原有大小写形式。
 * 返回原值（已包含时）或新 PATH。
 */
export function prependAgentCliShimPath(
  pathValue: string | undefined,
  shimDir: string,
  platform: NodeJS.Platform = process.platform,
): string {
  const current = pathValue ?? "";
  const separator = pathDelimiter(platform);
  const entries = current.split(separator).filter(Boolean);
  if (entries.includes(shimDir)) return current;
  return [shimDir, ...entries].join(separator);
}

export interface AgentCliShimInvocation {
  /** 直接执行的可执行文件：Node、Electron helper 或独立二进制。 */
  command: string;
  /** 传入的第一个脚本参数；独立二进制（SEA）省略。 */
  entry?: string;
  /** Electron 打包态必须以纯 Node 模式启动。 */
  electronRunAsNode?: boolean;
}

function quotePosix(value: string): string {
  return `'${value.replace(/'/gu, `'\\''`)}'`;
}

function quoteWindows(value: string): string {
  return `"${value.replace(/"/gu, '""')}"`;
}

/** POSIX shim：git-bash、Linux、macOS 共用（无扩展名文件）。 */
export function buildAgentCliPosixShim(invocation: AgentCliShimInvocation): string {
  const environment = invocation.electronRunAsNode ? "ELECTRON_RUN_AS_NODE=1 " : "";
  const args = [invocation.command, ...(invocation.entry ? [invocation.entry] : [])]
    .map(quotePosix)
    .join(" ");
  return [
    "#!/bin/sh",
    "# Generated by KayingCode. Do not edit.",
    `exec ${environment}${args} "$@"`,
    "",
  ].join("\n");
}

/** Windows cmd shim：供 cmd/PowerShell 使用；git-bash 命中无扩展名 POSIX 脚本。 */
export function buildAgentCliWindowsShim(invocation: AgentCliShimInvocation): string {
  const args = [invocation.command, ...(invocation.entry ? [invocation.entry] : [])]
    .map(quoteWindows)
    .join(" ");
  return [
    "@echo off",
    "setlocal",
    ...(invocation.electronRunAsNode ? ['set "ELECTRON_RUN_AS_NODE=1"'] : []),
    `${args} %*`,
    "",
  ].join("\r\n");
}
