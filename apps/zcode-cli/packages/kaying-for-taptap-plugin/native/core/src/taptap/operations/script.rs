//! TapTap script operations — list, create, attach.

use crate::model::{ExecuteError, OperationPlan, OperationRequest, OperationResult, PrepareError};
use serde_json::json;
use std::path::Path;
use std::sync::Arc;
use std::sync::atomic::{AtomicU64, Ordering};
use tracing::info;

static PLAN_COUNTER: AtomicU64 = AtomicU64::new(0);

/// Handle `script.list` — list all Lua scripts in the scripts/ directory and subdirectories.
pub fn script_list(request: &OperationRequest) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let scripts_dir = root.join("scripts");

    if !scripts_dir.is_dir() {
        return Ok(OperationResult {
            request_id: request.request_id.clone(),
            success: false,
            output: json!({
                "error": "No scripts/ directory found",
                "project_root": root.to_string_lossy()
            }),
            exit_code: Some(1),
            duration_ms: 0,
            log_path: None,
        });
    }

    let mut scripts: Vec<String> = Vec::new();
    collect_lua_scripts(&scripts_dir, &scripts_dir, &mut scripts)
        .map_err(|e| ExecuteError::Io(e))?;

    scripts.sort();

    info!(
        project_root = %root.to_string_lossy(),
        count = scripts.len(),
        "Scripts listed"
    );

    Ok(OperationResult {
        request_id: request.request_id.clone(),
        success: true,
        output: json!({
            "scripts": scripts,
            "count": scripts.len(),
            "project_root": root.to_string_lossy()
        }),
        exit_code: Some(0),
        duration_ms: 0,
        log_path: None,
    })
}

/// Handle `script.create` — create a new Lua script file with a basic template.
pub fn script_create(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;

    let script_name = request
        .arguments
        .get("name")
        .and_then(|v| v.as_str())
        .unwrap_or("script");
    let script_path_str = request
        .arguments
        .get("path")
        .and_then(|v| v.as_str())
        .unwrap_or("");

    // Determine the full path: if `path` is provided, use it relative to scripts/;
    // otherwise use scripts/{name}.lua. Strip a leading "scripts/" prefix if the
    // caller already included it, to avoid path doubling.
    let relative_path = if script_path_str.is_empty() {
        format!("{}.lua", script_name)
    } else {
        script_path_str
            .strip_prefix("scripts/")
            .unwrap_or(script_path_str)
            .to_string()
    };

    // Ensure the path has a .lua extension
    let relative_path = if relative_path.ends_with(".lua") {
        relative_path
    } else {
        format!("{}.lua", relative_path)
    };

    let scripts_dir = root.join("scripts");
    let target_path = scripts_dir.join(&relative_path);

    // Create parent directories if needed
    if let Some(parent) = target_path.parent() {
        if !parent.exists() {
            std::fs::create_dir_all(parent).map_err(|e| ExecuteError::Io(e))?;
        }
    }

    // Check if file already exists
    if target_path.exists() {
        return Ok(OperationResult {
            request_id: request.request_id.clone(),
            success: false,
            output: json!({
                "error": "Script already exists",
                "path": relative_path,
                "project_root": root.to_string_lossy()
            }),
            exit_code: Some(1),
            duration_ms: 0,
            log_path: None,
        });
    }

    // Write the Lua template
    let template = format!(
        r#"-- {}.lua
-- Auto-generated by kaying-for-taptap-core

function init(self)
    -- Called when the script is initialized
end

function update(self, dt)
    -- Called every frame
    -- dt: delta time in seconds
end

function on_message(self, message, sender)
    -- Called when a message is received
end
"#,
        script_name.trim_end_matches(".lua")
    );

    std::fs::write(&target_path, &template).map_err(|e| ExecuteError::Io(e))?;

    info!(
        project_root = %root.to_string_lossy(),
        path = %relative_path,
        "Script created"
    );

    Ok(OperationResult {
        request_id: request.request_id.clone(),
        success: true,
        output: json!({
            "created": true,
            "path": relative_path,
            "full_path": target_path.to_string_lossy(),
            "project_root": root.to_string_lossy()
        }),
        exit_code: Some(0),
        duration_ms: 0,
        log_path: None,
    })
}

/// Handle `script.attach` — associate a script with a scene node.
///
/// Records the association in `.project/scripts.json`.
pub fn script_attach(request: &OperationRequest) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;

    let script_path_raw = request
        .arguments
        .get("script_path")
        .and_then(|v| v.as_str())
        .ok_or_else(|| ExecuteError::NotPrepared("Missing script_path argument".to_string()))?;
    // Strip a leading "scripts/" prefix if the caller already included it,
    // to avoid path doubling when joining with the scripts/ directory.
    let script_path = script_path_raw
        .strip_prefix("scripts/")
        .unwrap_or(script_path_raw);
    let node_path = request
        .arguments
        .get("node_path")
        .and_then(|v| v.as_str())
        .ok_or_else(|| ExecuteError::NotPrepared("Missing node_path argument".to_string()))?;

    // Verify the script file exists
    let scripts_dir = root.join("scripts");
    let full_script_path = scripts_dir.join(script_path);
    if !full_script_path.exists() {
        return Ok(OperationResult {
            request_id: request.request_id.clone(),
            success: false,
            output: json!({
                "error": "Script file not found",
                "script_path": script_path,
                "full_path": full_script_path.to_string_lossy(),
                "project_root": root.to_string_lossy()
            }),
            exit_code: Some(1),
            duration_ms: 0,
            log_path: None,
        });
    }

    // Ensure .project directory exists
    let project_dir = root.join(".project");
    std::fs::create_dir_all(&project_dir).map_err(|e| ExecuteError::Io(e))?;

    // Read existing scripts.json or create a new one
    let scripts_json_path = project_dir.join("scripts.json");
    let mut registry: serde_json::Value = if scripts_json_path.exists() {
        let content =
            std::fs::read_to_string(&scripts_json_path).map_err(|e| ExecuteError::Io(e))?;
        serde_json::from_str(&content).unwrap_or_else(|_| {
            json!({
                "scripts": [],
                "attachments": {}
            })
        })
    } else {
        json!({
            "scripts": [],
            "attachments": {}
        })
    };

    // Ensure the script is registered in the scripts list
    let scripts_list = registry
        .get_mut("scripts")
        .and_then(|v| v.as_array_mut())
        .unwrap(); // Safe because we initialized it above

    if !scripts_list.iter().any(|s| s.as_str() == Some(script_path)) {
        scripts_list.push(json!(script_path));
    }

    // Record the attachment
    let attachments = registry
        .get_mut("attachments")
        .and_then(|v| v.as_object_mut())
        .unwrap(); // Safe because we initialized it above

    // Get existing attachments for this node, or create an empty array
    let node_scripts = attachments
        .entry(node_path.to_string())
        .or_insert_with(|| json!([]));
    let node_scripts_arr = node_scripts.as_array_mut().unwrap();

    if !node_scripts_arr
        .iter()
        .any(|s| s.as_str() == Some(script_path))
    {
        node_scripts_arr.push(json!(script_path));
    }

    // Write back
    std::fs::write(
        &scripts_json_path,
        serde_json::to_string_pretty(&registry).unwrap(),
    )
    .map_err(|e| ExecuteError::Io(e))?;

    info!(
        project_root = %root.to_string_lossy(),
        script = %script_path,
        node = %node_path,
        "Script attached to node"
    );

    Ok(OperationResult {
        request_id: request.request_id.clone(),
        success: true,
        output: json!({
            "attached": true,
            "script_path": script_path,
            "node_path": node_path,
            "registry_path": scripts_json_path.to_string_lossy(),
            "project_root": root.to_string_lossy()
        }),
        exit_code: Some(0),
        duration_ms: 0,
        log_path: None,
    })
}

/// Prepare a script operation — validate arguments and return a plan.
pub fn prepare_script(request: &OperationRequest) -> Result<OperationPlan, PrepareError> {
    let _root =
        get_project_root(request).map_err(|e| PrepareError::InvalidArguments(e.to_string()))?;

    let plan_id = format!("plan-{}", PLAN_COUNTER.fetch_add(1, Ordering::SeqCst));
    let now = chrono::Utc::now();

    let effects = match request.operation_id.as_str() {
        "script.create" => vec![crate::model::Effect::WriteProject],
        "script.attach" => vec![crate::model::Effect::WriteProject],
        _ => vec![],
    };

    let targets = match request.operation_id.as_str() {
        "script.create" => {
            let script_name = request
                .arguments
                .get("name")
                .and_then(|v| v.as_str())
                .unwrap_or("script");
            vec![format!("scripts/{}.lua", script_name)]
        }
        "script.attach" => {
            vec![".project/scripts.json".to_string()]
        }
        _ => vec![],
    };

    Ok(OperationPlan {
        plan_id,
        normalized_operation: request.operation_id.clone(),
        normalized_arguments: request.arguments.clone(),
        targets,
        effects,
        project_fingerprint: None,
        expires_at: (now + chrono::Duration::minutes(5)).to_rfc3339(),
        effect_digest: "script-effects".to_string(),
    })
}

fn get_project_root(request: &OperationRequest) -> Result<Arc<Path>, ExecuteError> {
    let root_str = request
        .arguments
        .get("project_root")
        .and_then(|v| v.as_str())
        .or_else(|| request.project_root.as_ref().and_then(|p| p.to_str()))
        .ok_or_else(|| ExecuteError::NotPrepared("Missing project_root argument".to_string()))?;

    let path = std::path::PathBuf::from(root_str);
    if !path.exists() {
        return Err(ExecuteError::ExternalToolFailed(format!(
            "Project root does not exist: {}",
            path.display()
        )));
    }

    Ok(Arc::from(path))
}

/// Recursively collect all Lua script files under a directory.
fn collect_lua_scripts(
    dir: &Path,
    base_dir: &Path,
    scripts: &mut Vec<String>,
) -> std::io::Result<()> {
    let entries = std::fs::read_dir(dir)?;
    for entry in entries {
        let entry = entry?;
        let path = entry.path();
        if path.is_dir() {
            collect_lua_scripts(&path, base_dir, scripts)?;
        } else if path.extension().map_or(false, |ext| ext == "lua") {
            if let Ok(relative) = path.strip_prefix(base_dir) {
                scripts.push(relative.to_string_lossy().to_string());
            }
        }
    }
    Ok(())
}
