//! TapTap debug/diagnostic operations — profiler, metrics, diagnostics export.
//!
//! Generated profiler code lives under `scripts/systems/profiler.lua`.
//! Diagnostics snapshots are written to `.project/diagnostics/`.

use crate::model::{
    Effect, ExecuteError, OperationPlan, OperationRequest, OperationResult, PrepareError,
};
use crate::taptap::operations::helpers::{
    get_project_root, make_plan, ok_result, read_json_file_opt, required_str_arg, str_arg,
    write_json_file,
};
use serde_json::json;
use std::path::{Path, PathBuf};
use std::sync::atomic::AtomicU64;
use std::time::{Instant, SystemTime, UNIX_EPOCH};
use tracing::info;

static PLAN_COUNTER: AtomicU64 = AtomicU64::new(0);

fn systems_dir(root: &Path) -> PathBuf {
    root.join("scripts").join("systems")
}

fn profiler_lua(root: &Path) -> PathBuf {
    systems_dir(root).join("profiler.lua")
}

fn diagnostics_dir(root: &Path) -> PathBuf {
    root.join(".project").join("diagnostics")
}

fn ensure_parent(path: &Path) -> Result<(), ExecuteError> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(ExecuteError::Io)?;
    }
    Ok(())
}

fn ensure_profiler_lua(root: &Path) -> Result<(), ExecuteError> {
    let path = profiler_lua(root);
    if !path.exists() {
        let body = "-- profiler.lua — Performance profiler facade\n-- Auto-generated by debug operations.\n\nlocal Profiler = {\n    running = false,\n    samples = {},\n    start_time = 0,\n}\nreturn Profiler\n";
        ensure_parent(&path)?;
        std::fs::write(&path, body).map_err(ExecuteError::Io)?;
    }
    Ok(())
}

fn append_to_profiler(root: &Path, snippet: &str, marker: &str) -> Result<bool, ExecuteError> {
    let path = profiler_lua(root);
    ensure_profiler_lua(root)?;
    let mut content = std::fs::read_to_string(&path).map_err(ExecuteError::Io)?;
    if content.contains(marker) {
        Ok(false)
    } else {
        content.push_str(snippet);
        std::fs::write(&path, &content).map_err(ExecuteError::Io)?;
        Ok(true)
    }
}

