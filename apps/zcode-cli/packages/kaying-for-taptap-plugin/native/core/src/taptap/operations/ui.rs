/// Handle `ui.inspect` — statically scan UI modules and return an element tree.
pub fn ui_inspect(request: &OperationRequest) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let dir = ui_dir(&root);
    let mut tree: Vec<serde_json::Value> = Vec::new();
    if dir.exists() {
        scan_ui_dir(&dir, &dir, &mut tree).map_err(ExecuteError::Io)?;
    }
    info!(count = tree.len(), "UI tree inspected");
    Ok(ok_result(
        request,
        json!({
            "modules": tree,
            "count": tree.len(),
            "ui_dir": dir.to_string_lossy(),
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

fn scan_ui_dir(
    base: &Path,
    dir: &Path,
    out: &mut Vec<serde_json::Value>,
) -> Result<(), std::io::Error> {
    for entry in std::fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.is_dir() {
            scan_ui_dir(base, &path, out)?;
        } else if path.is_file() && path.extension().map(|e| e == "lua").unwrap_or(false) {
            let rel = path
                .strip_prefix(base)
                .unwrap_or(&path)
                .to_string_lossy()
                .to_string();
            let content = std::fs::read_to_string(&path)?;
            let elements = extract_element_names(&content);
            let functions = extract_function_names(&content);
            out.push(json!({
                "path": rel,
                "name": path.file_stem().and_then(|n| n.to_str()).unwrap_or(""),
                "size": content.len(),
                "elements": elements,
                "functions": functions,
            }));
        }
    }
    Ok(())
}

/// Extract element names from `.create<Name>` patterns.
fn extract_element_names(content: &str) -> Vec<String> {
    let mut out = Vec::new();
    for line in content.lines() {
        if let Some(idx) = line.find("M.create") {
            let after = &line[idx + "M.create".len()..];
            let name: String = after
                .chars()
                .take_while(|c| c.is_alphanumeric() || *c == '_')
                .collect();
            if !name.is_empty() {
                out.push(name);
            }
        }
    }
    out
}

/// Extract top-level function names from a Lua module.
fn extract_function_names(content: &str) -> Vec<String> {
    let mut out = Vec::new();
    for line in content.lines() {
        let trimmed = line.trim_start();
        if let Some(rest) = trimmed.strip_prefix("function ") {
            let name: String = rest
                .chars()
                .take_while(|c| c.is_alphanumeric() || *c == '_' || *c == ':' || *c == '.')
                .collect();
            if !name.is_empty() {
                out.push(name);
            }
        }
    }
    out
}

