/// Handle `debug.start_profiler` — generate performance collection code.
pub fn debug_start_profiler(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let sample_interval_ms = request
        .arguments
        .get("sample_interval_ms")
        .and_then(|v| v.as_u64())
        .unwrap_or(16);
    let max_samples = request
        .arguments
        .get("max_samples")
        .and_then(|v| v.as_u64())
        .unwrap_or(1000);

    let marker = "-- @debug.start_profiler";
    let snippet = format!(
        "\n{marker}\n-- Start performance sampling (interval={iv}ms, max={mx})\nfunction Profiler.start()\n    Profiler.running = true\n    Profiler.start_time = os.clock()\n    Profiler.samples = {{}}\n    Profiler.sample_interval = {iv}\n    Profiler.max_samples = {mx}\nend\n",
        iv = sample_interval_ms,
        mx = max_samples
    );

    let appended = append_to_profiler(&root, &snippet, marker)?;
    let path = profiler_lua(&root);

    info!(appended, path = %path.to_string_lossy(), "Profiler start generated");

    Ok(ok_result(
        request,
        json!({
            "generated": true,
            "appended": appended,
            "sample_interval_ms": sample_interval_ms,
            "max_samples": max_samples,
            "path": path.to_string_lossy(),
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

