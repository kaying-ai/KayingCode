//! TapTap UI operations — canvas, elements, layout, events, widgets.
//!
//! All operations generate Lua code under `scripts/ui/` following the modular contract.
//! Widgets are minimal, runnable templates — Agents refine via file edits.

use crate::model::{
    Effect, ExecuteError, OperationPlan, OperationRequest, OperationResult, PrepareError,
};
use crate::taptap::operations::helpers::{
    fail_result, get_project_root, make_plan, ok_result, required_str_arg, str_arg,
};
use serde_json::json;
use std::path::{Path, PathBuf};
use std::sync::atomic::AtomicU64;
use std::time::Instant;
use tracing::info;

static PLAN_COUNTER: AtomicU64 = AtomicU64::new(0);

fn ui_dir(root: &Path) -> PathBuf {
    root.join("scripts").join("ui")
}

fn widgets_dir(root: &Path) -> PathBuf {
    ui_dir(root).join("widgets")
}

fn ensure_parent(path: &Path) -> Result<(), ExecuteError> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(ExecuteError::Io)?;
    }
    Ok(())
}

/// Convert a snake_case name to PascalCase for Lua identifiers.
fn pascal(name: &str) -> String {
    name.split('_')
        .map(|w| {
            let mut c = w.chars();
            match c.next() {
                Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

