/// Handle `vfx.create_trail` — generate a trail code module.
pub fn vfx_create_trail(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let path = vfx_modules_dir(&root).join(format!("trail_{name}.lua"));
    let body = format!(
        "-- trail_{name}.lua — Trail VFX module\n-- Auto-generated by vfx.create_trail.\n\nlocal Trail = {{}}\nTrail.__index = Trail\n\nfunction Trail.new(maxPoints, width)\n  local self = setmetatable({{}}, Trail)\n  self.maxPoints = maxPoints or 30\n  self.width = width or 0.1\n  self.points = {{}}\n  return self\nend\n\nfunction Trail:addPoint(x, y, z)\n  table.insert(self.points, {{x = x, y = y, z = z}})\n  if #self.points > self.maxPoints then\n    table.remove(self.points, 1)\n  end\nend\n\nfunction Trail:draw(nvg)\n  -- TODO: render a strip between consecutive points\nend\n\nreturn Trail\n"
    );
    ensure_parent(&path)?;
    std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    info!(name = %name, "Trail module created");
    Ok(ok_result(
        request,
        json!({"created": true, "name": name, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

