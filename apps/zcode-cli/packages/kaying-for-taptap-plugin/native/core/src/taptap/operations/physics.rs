/// Handle `physics.set_collision_layer` — set a body's collision mask.
pub fn physics_set_collision_layer(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let layer = request
        .arguments
        .get("layer")
        .and_then(|v| v.as_u64())
        .unwrap_or(0);
    let mask = request
        .arguments
        .get("mask")
        .and_then(|v| v.as_u64())
        .unwrap_or(0xFFFF);

    let mut overrides = read_overrides(&root);
    let mut updated = false;
    if let Some(bodies) = overrides.get_mut("bodies").and_then(|v| v.as_array_mut()) {
        for body in bodies {
            if body.get("name").and_then(|v| v.as_str()) == Some(&name) {
                body["layer"] = json!(layer);
                body["mask"] = json!(mask);
                updated = true;
                break;
            }
        }
    }
    if !updated {
        return Ok(fail_result(
            request,
            json!({"error": format!("Rigidbody '{name}' not found")}),
            started.elapsed().as_millis() as u64,
        ));
    }
    write_overrides(&root, &overrides)?;
    info!(name = %name, layer, mask, "Collision layer set");
    Ok(ok_result(
        request,
        json!({"set": updated, "name": name, "layer": layer, "mask": mask, "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

