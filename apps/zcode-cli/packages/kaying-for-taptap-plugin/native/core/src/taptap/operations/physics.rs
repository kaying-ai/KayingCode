/// Handle `physics.raycast` — generate a raycast query helper in physics.lua.
pub fn physics_raycast(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    ensure_physics_lua(&root)?;
    let path = physics_lua(&root);
    let snippet = format!(
        "\nfunction Physics.raycast_{name}(origin, direction, maxDist)\n  -- TODO: bridge to engine physics world; return hit info table or nil\n  return nil\nend\n"
    );
    let mut content = std::fs::read_to_string(&path).map_err(ExecuteError::Io)?;
    let func_name = format!("Physics.raycast_{name}");
    if !content.contains(&func_name) {
        content.push_str(&snippet);
        std::fs::write(&path, &content).map_err(ExecuteError::Io)?;
    }
    info!(name = %name, "Raycast helper added");
    Ok(ok_result(
        request,
        json!({"added": true, "name": name, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

