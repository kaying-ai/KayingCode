/// Handle `ui.set_layout` — append/replace a layout block on a UI module.
pub fn ui_set_layout(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let module = required_str_arg(request, "module")?;
    let layout = request
        .arguments
        .get("layout")
        .cloned()
        .unwrap_or(json!({}));
    let layout_str = serde_json::to_string_pretty(&layout).unwrap_or_default();
    let path = ui_dir(&root).join(format!("{module}.lua"));

    let marker = "-- LAYOUT BEGIN";
    let end_marker = "-- LAYOUT END";
    let block = format!("{marker}\nM.layout = {layout_str}\n{end_marker}\n");

    let mut content = std::fs::read_to_string(&path).map_err(ExecuteError::Io)?;
    if let Some(start) = content.find(marker) {
        if let Some(end) = content.find(end_marker) {
            content.replace_range(start..end + end_marker.len(), block.trim_end());
        } else {
            content.push_str(&block);
        }
    } else {
        content.push_str(&block);
    }
    std::fs::write(&path, &content).map_err(ExecuteError::Io)?;
    info!(module = %module, "Layout updated");
    Ok(ok_result(
        request,
        json!({"updated": true, "module": module, "layout": layout, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

