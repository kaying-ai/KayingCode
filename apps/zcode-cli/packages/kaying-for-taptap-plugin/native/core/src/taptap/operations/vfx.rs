/// Handle `vfx.set_properties` — patch a particle emitter file.
pub fn vfx_set_properties(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let path = vfx_dir(&root).join(format!("{name}.particle.json"));
    let Some(mut emitter) = read_json_file_opt(&path).map_err(ExecuteError::Io)? else {
        return Ok(fail_result(
            request,
            json!({"error": format!("Emitter '{name}' not found")}),
            started.elapsed().as_millis() as u64,
        ));
    };
    let props = request
        .arguments
        .get("properties")
        .cloned()
        .unwrap_or(json!({}));
    let mut updated = 0;
    if let (Some(obj), Some(props_obj)) = (emitter.as_object_mut(), props.as_object()) {
        for (k, v) in props_obj {
            obj.insert(k.clone(), v.clone());
            updated += 1;
        }
    }
    write_json_file(&path, &emitter).map_err(ExecuteError::Io)?;
    info!(name = %name, updated, "Emitter properties updated");
    Ok(ok_result(
        request,
        json!({"updated": updated, "name": name, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

