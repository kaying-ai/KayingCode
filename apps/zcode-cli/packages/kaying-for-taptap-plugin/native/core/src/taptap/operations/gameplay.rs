//! TapTap gameplay operations — state machines, behavior trees, content tables.
//!
//! State machines live at `scripts/gameplay/state_machine.lua`. Behavior
//! trees live under `scripts/gameplay/bt/`. Content tables (spawn, loot,
//! quests, dialogues) live under `scripts/data/`.

use crate::model::{
    Effect, ExecuteError, OperationPlan, OperationRequest, OperationResult, PrepareError,
};
use crate::taptap::operations::helpers::{
    fail_result, get_project_root, make_plan, ok_result, read_json_file_opt, required_str_arg,
    str_arg, write_json_file,
};
use serde_json::json;
use std::path::{Path, PathBuf};
use std::sync::atomic::AtomicU64;
use std::time::Instant;
use tracing::info;

static PLAN_COUNTER: AtomicU64 = AtomicU64::new(0);

fn gameplay_dir(root: &Path) -> PathBuf {
    root.join("scripts").join("gameplay")
}

fn bt_dir(root: &Path) -> PathBuf {
    gameplay_dir(root).join("bt")
}

fn data_dir(root: &Path) -> PathBuf {
    root.join("scripts").join("data")
}

fn ensure_parent(path: &Path) -> Result<(), ExecuteError> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(ExecuteError::Io)?;
    }
    Ok(())
}

