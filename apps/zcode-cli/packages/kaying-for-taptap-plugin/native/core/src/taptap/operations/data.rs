/// Handle `data.set_locale` — update `project.json.locale`.
pub fn data_set_locale(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let locale = required_str_arg(request, "locale")?;

    let path = project_json(&root);
    let mut proj = read_json_file_opt(&path)
        .map_err(ExecuteError::Io)?
        .unwrap_or(json!({}));
    let prev = proj
        .get("locale")
        .and_then(|v| v.as_str())
        .unwrap_or("")
        .to_string();
    if let Some(obj) = proj.as_object_mut() {
        obj.insert("locale".to_string(), json!(locale));
    }
    write_json_file(&path, &proj).map_err(ExecuteError::Io)?;
    info!(locale = %locale, prev = %prev, "Locale updated");
    Ok(ok_result(
        request,
        json!({
            "updated": true,
            "locale": locale,
            "previous": prev,
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

