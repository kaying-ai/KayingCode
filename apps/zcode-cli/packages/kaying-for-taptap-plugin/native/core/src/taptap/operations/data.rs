/// Handle `data.migrate` — append migration step to `scripts/data/save.lua`.
pub fn data_migrate(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let from = required_str_arg(request, "from_version")?;
    let to = required_str_arg(request, "to_version")?;

    let path = data_dir(&root).join("save.lua");
    let snippet = format!(
        "\nfunction Save.migrate_{from}_to_{to}(data)\n  -- TODO: transform data from schema {from} to {to}\n  return data\nend\n"
    );

    if !path.exists() {
        let body = format!("-- save.lua\nlocal Save = {{}}\n{snippet}\nreturn Save\n");
        ensure_parent(&path)?;
        std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    } else {
        let mut content = std::fs::read_to_string(&path).map_err(ExecuteError::Io)?;
        let func_name = format!("Save.migrate_{from}_to_{to}");
        if !content.contains(&func_name) {
            content.push_str(&snippet);
            std::fs::write(&path, &content).map_err(ExecuteError::Io)?;
        } else {
            return Ok(fail_result(
                request,
                json!({
                    "error": format!("Migration {from}->{to} already exists"),
                    "path": path.to_string_lossy(),
                }),
                started.elapsed().as_millis() as u64,
            ));
        }
    }

    info!(from = %from, to = %to, path = %path.to_string_lossy(), "Migration step added");
    Ok(ok_result(
        request,
        json!({
            "added": true,
            "from_version": from,
            "to_version": to,
            "path": path.to_string_lossy(),
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

