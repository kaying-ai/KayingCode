/// Prepare a network operation.
pub fn prepare_network(request: &OperationRequest) -> Result<OperationPlan, PrepareError> {
    let effects = vec![Effect::ReadProject, Effect::WriteProject];
    let _ = request.operation_id.as_str();
    make_plan(request, &PLAN_COUNTER, effects, "network-effects")
}
