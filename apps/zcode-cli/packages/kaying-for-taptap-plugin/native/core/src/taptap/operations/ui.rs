/// Prepare a UI operation.
pub fn prepare_ui(request: &OperationRequest) -> Result<OperationPlan, PrepareError> {
    let effects = match request.operation_id.as_str() {
        "ui.inspect" => vec![Effect::ReadProject],
        _ => vec![Effect::ReadProject, Effect::WriteProject],
    };
    make_plan(request, &PLAN_COUNTER, effects, "ui-effects")
}
