/// Handle `gameplay.validate` — statically validate state machine/BT graphs.
pub fn gameplay_validate(request: &OperationRequest) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let mut checks: Vec<serde_json::Value> = Vec::new();

    // Validate state machine manifests: every transition target must exist as a state.
    let gameplay = gameplay_dir(&root);
    if gameplay.exists() {
        if let Ok(entries) = std::fs::read_dir(&gameplay) {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.extension().map(|e| e == "json").unwrap_or(false) {
                    if let Some(stem) = path.file_stem().and_then(|s| s.to_str()) {
                        if !stem.ends_with(".states") {
                            continue;
                        }
                        let sm_name = stem.trim_end_matches(".states");
                        if let Ok(Some(manifest)) = read_json_file_opt(&path) {
                            let states: Vec<String> = manifest
                                .get("states")
                                .and_then(|v| v.as_array())
                                .map(|arr| {
                                    arr.iter()
                                        .filter_map(|s| {
                                            s.get("name").and_then(|v| v.as_str()).map(String::from)
                                        })
                                        .collect()
                                })
                                .unwrap_or_default();
                            let transitions =
                                manifest.get("transitions").and_then(|v| v.as_array());
                            if let Some(transitions) = transitions {
                                for t in transitions {
                                    let from = t.get("from").and_then(|v| v.as_str()).unwrap_or("");
                                    let to = t.get("to").and_then(|v| v.as_str()).unwrap_or("");
                                    if !states.iter().any(|s| s == from) {
                                        checks.push(json!({"sm": sm_name, "issue": "transition_from_missing", "from": from}));
                                    }
                                    if !states.iter().any(|s| s == to) {
                                        checks.push(json!({"sm": sm_name, "issue": "transition_to_missing", "to": to}));
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    let valid = checks.is_empty();
    info!(checks = checks.len(), valid, "Gameplay graph validated");
    Ok(ok_result(
        request,
        json!({"valid": valid, "checks": checks, "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

