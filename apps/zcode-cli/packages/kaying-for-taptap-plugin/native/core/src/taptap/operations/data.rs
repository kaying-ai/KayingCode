/// Handle `data.create_config` — write `scripts/data/<name>_config.lua`.
pub fn data_create_config(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let config = request
        .arguments
        .get("config")
        .cloned()
        .unwrap_or(json!({}));
    let entries_lua = config
        .as_object()
        .map(|o| {
            o.iter()
                .map(|(k, v)| format!("  {k} = {}", lua_value(v)))
                .collect::<Vec<_>>()
                .join(",\n")
        })
        .unwrap_or_default();

    let body = format!(
        "-- {name}_config.lua — Game config table\n-- Auto-generated by data.create_config.\n\nlocal Config = {{\n{entries_lua}\n}}\n\nreturn Config\n"
    );

    let path = data_dir(&root).join(format!("{name}_config.lua"));
    ensure_parent(&path)?;
    std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    info!(name = %name, path = %path.to_string_lossy(), "Config table created");
    Ok(ok_result(
        request,
        json!({
            "created": true,
            "name": name,
            "path": path.to_string_lossy(),
            "entries": config.as_object().map(|o| o.len()).unwrap_or(0),
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

/// Convert a JSON value to a Lua literal.
fn lua_value(v: &serde_json::Value) -> String {
    match v {
        serde_json::Value::Null => "nil".to_string(),
        serde_json::Value::Bool(b) => b.to_string(),
        serde_json::Value::Number(n) => n.to_string(),
        serde_json::Value::String(s) => format!("\"{}\"", s.replace('"', "\\\"")),
        serde_json::Value::Array(arr) => {
            let items = arr.iter().map(lua_value).collect::<Vec<_>>().join(", ");
            format!("{{ {items} }}")
        }
        serde_json::Value::Object(obj) => {
            let items = obj
                .iter()
                .map(|(k, v)| format!("{k} = {}", lua_value(v)))
                .collect::<Vec<_>>()
                .join(", ");
            format!("{{ {items} }}")
        }
    }
}

