/// Handle `physics.create_character_controller` — generate a controller module.
pub fn physics_create_character_controller(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let height = request
        .arguments
        .get("height")
        .and_then(|v| v.as_f64())
        .unwrap_or(1.8);
    let radius = request
        .arguments
        .get("radius")
        .and_then(|v| v.as_f64())
        .unwrap_or(0.3);
    let path = root
        .join("scripts")
        .join("systems")
        .join("character_controllers")
        .join(format!("{name}.lua"));
    let body = format!(
        "-- character_controllers/{name}.lua\n-- Auto-generated by physics.create_character_controller.\n\nlocal {Name} = {{}}\n{Name}.__index = {Name}\n\nfunction {Name}.new()\n  local self = setmetatable({{}}, {Name})\n  self.height = {height}\n  self.radius = {radius}\n  self.velocity = {{ x = 0, y = 0, z = 0 }}\n  self.grounded = false\n  return self\nend\n\nfunction {Name}:move(dx, dy, dz, dt)\n  -- TODO: bridge to engine character controller API\nend\n\nfunction {Name}:jump()\n  if self.grounded then self.velocity.y = 5.0 end\nend\n\nreturn {Name}\n",
        Name = name
            .chars()
            .next()
            .map(|c| c.to_ascii_uppercase().to_string())
            .unwrap_or_else(|| "C".to_string())
            + &name[1.min(name.len())..]
    );
    ensure_parent(&path)?;
    std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    info!(name = %name, "Character controller created");
    Ok(ok_result(
        request,
        json!({"created": true, "name": name, "height": height, "radius": radius, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

