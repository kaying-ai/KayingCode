import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "oxfmt";
import { loadOfficialPluginCatalog, runtimePluginDefinitions } from "./official-plugin-catalog.mjs";

async function updateGeneratedFile(path, text, { check, staleMessage }) {
  const existing = await readFile(path, "utf8").catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
  // 启动指纹包含生成物的 mtime；相同内容也写入会让缓存每次失效，
  // 并在 Windows 上重复打开被监视文件。与 --check 使用同一换行口径，只写真正的变化。
  if (existing !== null && existing.replace(/\r\n/g, "\n") === text) return;
  if (check) throw new Error(staleMessage);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, text);
}

export async function generateOfficialPluginCatalog(root, { check = false } = {}) {
  const catalog = await loadOfficialPluginCatalog(root);
  const definitions = runtimePluginDefinitions(catalog);
  // JSON 字面量保留元数据原文并接受 tsc 契约校验，不把 listing 内容拼成可执行模板。
  const source = `// Generated by scripts/generate-official-plugin-catalog.mjs. Do not edit.\nimport type { OfficialPluginReleaseDefinition } from "./official-plugin-release.js";\n\nexport const GENERATED_OFFICIAL_PLUGIN_DEFINITIONS: readonly OfficialPluginReleaseDefinition[] = ${JSON.stringify(definitions, null, 2)};\n`;
  const formatting = await readFile(resolve(root, ".oxfmtrc.json"), "utf8")
    .then(JSON.parse)
    .catch((error) => {
      if (error.code === "ENOENT") return {};
      throw error;
    });
  const formatted = await format("official-plugin-catalog.generated.ts", source, formatting);
  if (formatted.errors.length) throw new Error("Unable to format generated plugin contracts");
  const text = formatted.code.replace(/\r\n/g, "\n");
  const path = resolve(
    root,
    "apps/zcode-cli/packages/contracts/src/plugins/official-plugin-catalog.generated.ts",
  );
  await updateGeneratedFile(path, text, {
    check,
    staleMessage: "Official plugin contracts are stale; run pnpm run source:plugins",
  });
  const defaultIds = definitions
    .filter(({ defaultEnabled }) => defaultEnabled === true)
    .map(({ name }) => `${name}@${catalog.marketplace}`);
  const defaultsPath = resolve(root, "packages/shared/src/official-plugin-defaults.generated.ts");
  const defaults = await format(
    "official-plugin-defaults.generated.ts",
    `// Generated by scripts/generate-official-plugin-catalog.mjs. Do not edit.\nexport const GENERATED_DEFAULT_OFFICIAL_PLUGIN_IDS: readonly string[] = ${JSON.stringify(defaultIds)};\n`,
    formatting,
  );
  if (defaults.errors.length) throw new Error("Unable to format generated plugin defaults");
  const defaultsText = defaults.code.replace(/\r\n/g, "\n");
  await updateGeneratedFile(defaultsPath, defaultsText, {
    check,
    staleMessage: "Official plugin shared defaults are stale; run pnpm run source:plugins",
  });
  return catalog;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = fileURLToPath(new URL("..", import.meta.url));
  const catalog = await generateOfficialPluginCatalog(root, {
    check: process.argv.includes("--check"),
  });
  if (process.argv.includes("--runtime"))
    await loadOfficialPluginCatalog(root, {
      target: process.argv.find((value) => value.startsWith("--target="))?.slice(9),
      requireRuntime: true,
    });
  process.stdout.write(
    `official plugin catalog: OK (${catalog.plugins.length} release entries, ${catalog.compatibilityDefinitions.length} compatibility-only)\n`,
  );
}
