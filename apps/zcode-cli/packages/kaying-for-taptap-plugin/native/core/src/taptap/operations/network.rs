// ============================================================

/// Handle `network.configure_matchmaking` — write matchmaking config.
pub fn network_configure_matchmaking(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let region = str_arg(request, "region", "cn-east-1");
    let max_players = request
        .arguments
        .get("max_players")
        .and_then(|v| v.as_u64())
        .unwrap_or(4);
    let timeout = request
        .arguments
        .get("timeout_seconds")
        .and_then(|v| v.as_u64())
        .unwrap_or(30);
    let config = json!({
        "region": region,
        "max_players": max_players,
        "timeout_seconds": timeout,
    });
    let path = network_config(&root).with_file_name("matchmaking.json");
    let body = serde_json::to_string_pretty(&config).unwrap_or_default();
    ensure_parent(&path)?;
    std::fs::write(&path, body).map_err(ExecuteError::Io)?;
    info!(region = %region, max_players, "Matchmaking config written");
    Ok(ok_result(
        request,
        json!({"written": true, "config": config, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

