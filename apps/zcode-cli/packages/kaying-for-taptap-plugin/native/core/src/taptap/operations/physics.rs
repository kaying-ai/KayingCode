/// Handle `physics.create_rigidbody` — register a body in physics-overrides + physics.lua.
pub fn physics_create_rigidbody(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let body_type = str_arg(request, "body_type", "dynamic");
    let mass = request
        .arguments
        .get("mass")
        .and_then(|v| v.as_f64())
        .unwrap_or(1.0);
    let node_id = str_arg(request, "node_id", "");

    let entry = json!({"name": name, "body_type": body_type, "mass": mass, "node_id": node_id});
    append_to_overrides(&root, "bodies", entry.clone())?;

    // Ensure physics.lua exists with a bodies registry reference.
    ensure_physics_lua(&root)?;
    info!(name = %name, body_type = %body_type, "Rigidbody created");
    Ok(ok_result(
        request,
        json!({"created": true, "body": entry, "path": physics_overrides(&root).to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

/// Ensure `scripts/systems/physics.lua` exists with a basic module skeleton.
fn ensure_physics_lua(root: &Path) -> Result<(), ExecuteError> {
    let path = physics_lua(root);
    if !path.exists() {
        let body = "-- physics.lua — Physics system facade\n-- Auto-generated by physics operations.\n\nlocal Physics = {}\nlocal Overrides = require \"scripts.systems.physics_overrides\"\n\nfunction Physics.listBodies()\n  return Overrides.bodies or {}\nend\n\nreturn Physics\n";
        ensure_parent(&path)?;
        std::fs::write(&path, body).map_err(ExecuteError::Io)?;
    }
    Ok(())
}

