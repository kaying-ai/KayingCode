/// Handle `debug.assert_state` — generate an assertion function in profiler.lua.
pub fn debug_assert_state(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let condition = str_arg(request, "condition", "true");
    let message = str_arg(request, "message", "assertion failed");

    let safe_name = name.replace(|c: char| !c.is_alphanumeric() && c != '_', "_");
    let marker = format!("-- @debug.assert_state:{safe_name}");
    let snippet = format!(
        "\n{marker}\n-- Assert: {message}\nfunction Profiler.assert_{safe_name}()\n    assert(({cond}), \"{msg} [{name}]\")\nend\n",
        cond = condition,
        msg = message.replace('"', "'"),
        name = name
    );

    let appended = append_to_profiler(&root, &snippet, &marker)?;
    let path = profiler_lua(&root);

    info!(name = %name, appended, path = %path.to_string_lossy(), "Assertion generated");

    Ok(ok_result(
        request,
        json!({
            "generated": true,
            "appended": appended,
            "name": name,
            "condition": condition,
            "function": format!("Profiler.assert_{safe_name}"),
            "path": path.to_string_lossy(),
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

