/// Handle `physics.set_gravity` — update `project.json.physics.gravity`.
pub fn physics_set_gravity(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let gravity = request
        .arguments
        .get("gravity")
        .cloned()
        .unwrap_or(json!([0.0, -9.81, 0.0]));
    let path = project_json(&root);
    let mut proj = read_json_file_opt(&path)
        .map_err(ExecuteError::Io)?
        .unwrap_or(json!({}));
    let prev = proj.get("physics").cloned();
    if let Some(obj) = proj.as_object_mut() {
        let physics = obj
            .entry("physics")
            .or_insert_with(|| json!({}))
            .as_object_mut()
            .map(|p| {
                p.insert("gravity".to_string(), gravity.clone());
            });
        if physics.is_none() {
            // physics wasn't an object; replace it.
            obj.insert("physics".to_string(), json!({"gravity": gravity}));
        }
    }
    write_json_file(&path, &proj).map_err(ExecuteError::Io)?;
    info!(gravity = ?gravity, "Gravity set");
    Ok(ok_result(
        request,
        json!({"updated": true, "gravity": gravity, "previous": prev, "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

