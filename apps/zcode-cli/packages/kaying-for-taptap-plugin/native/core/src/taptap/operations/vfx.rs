//! TapTap VFX operations — particle emitters, trails, decals.
//!
//! Particle data lives under `assets/vfx/`. Generated play/stop helpers
//! append to `scripts/systems/vfx.lua`. Trail/decal code modules live under
//! `scripts/systems/vfx/`.

use crate::model::{
    Effect, ExecuteError, OperationPlan, OperationRequest, OperationResult, PrepareError,
};
use crate::taptap::operations::helpers::{
    fail_result, get_project_root, make_plan, ok_result, read_json_file_opt, required_str_arg,
    str_arg, write_json_file,
};
use serde_json::json;
use std::path::{Path, PathBuf};
use std::sync::atomic::AtomicU64;
use std::time::Instant;
use tracing::info;

static PLAN_COUNTER: AtomicU64 = AtomicU64::new(0);

fn vfx_dir(root: &Path) -> PathBuf {
    root.join("assets").join("vfx")
}

fn vfx_lua(root: &Path) -> PathBuf {
    root.join("scripts").join("systems").join("vfx.lua")
}

fn vfx_modules_dir(root: &Path) -> PathBuf {
    root.join("scripts").join("systems").join("vfx")
}

fn ensure_parent(path: &Path) -> Result<(), ExecuteError> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(ExecuteError::Io)?;
    }
    Ok(())
}

fn ensure_vfx_lua(root: &Path) -> Result<(), ExecuteError> {
    let path = vfx_lua(root);
    if !path.exists() {
        let body = "-- vfx.lua — VFX system facade\n-- Auto-generated by vfx operations.\n\nlocal Vfx = {}\nreturn Vfx\n";
        ensure_parent(&path)?;
        std::fs::write(&path, body).map_err(ExecuteError::Io)?;
    }
    Ok(())
}

fn append_to_vfx_lua(root: &Path, snippet: &str, marker: &str) -> Result<bool, ExecuteError> {
    let path = vfx_lua(root);
    ensure_vfx_lua(root)?;
    let mut content = std::fs::read_to_string(&path).map_err(ExecuteError::Io)?;
    if content.contains(marker) {
        Ok(false)
    } else {
        content.push_str(snippet);
        std::fs::write(&path, &content).map_err(ExecuteError::Io)?;
        Ok(true)
    }
}

