pub fn prepare_physics(request: &OperationRequest) -> Result<OperationPlan, PrepareError> {
    let effects = vec![Effect::ReadProject, Effect::WriteProject];
    let _ = request.operation_id.as_str();
    make_plan(request, &PLAN_COUNTER, effects, "physics-effects")
}
