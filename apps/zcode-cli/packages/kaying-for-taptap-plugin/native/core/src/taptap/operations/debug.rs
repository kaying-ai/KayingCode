/// Prepare a debug operation.
pub fn prepare_debug(request: &OperationRequest) -> Result<OperationPlan, PrepareError> {
    let effects = match request.operation_id.as_str() {
        "debug.get_frame_metrics" | "debug.export_diagnostics" => vec![Effect::ReadProject],
        _ => vec![Effect::ReadProject, Effect::WriteProject],
    };
    make_plan(request, &PLAN_COUNTER, effects, "debug-effects")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::OperationRequest;
    use serde_json::json;

    fn req(op: &str, root: &str) -> OperationRequest {
        OperationRequest {
            request_id: "test".to_string(),
            provider_id: "taptap".to_string(),
            operation_id: op.to_string(),
            project_root: None,
            arguments: json!({ "project_root": root }),
            timeout_ms: None,
            dry_run: false,
            plan_id: None,
            effect_digest: None,
        }
    }

    #[test]
    fn test_debug_start_profiler() {
        let temp = tempfile::tempdir().unwrap();
        let r = req("debug.start_profiler", temp.path().to_str().unwrap());
        let plan = prepare_debug(&r).unwrap();
        let res = debug_start_profiler(&r, &plan).unwrap();
        assert!(res.success);
        let path = profiler_lua(temp.path());
        assert!(path.exists());
        let content = std::fs::read_to_string(&path).unwrap();
        assert!(content.contains("Profiler.start"));
        assert!(content.contains("sample_interval"));
    }

    #[test]
    fn test_debug_stop_profiler() {
        let temp = tempfile::tempdir().unwrap();
        let r = req("debug.stop_profiler", temp.path().to_str().unwrap());
        let plan = prepare_debug(&r).unwrap();
        let res = debug_stop_profiler(&r, &plan).unwrap();
        assert!(res.success);
        let content = std::fs::read_to_string(profiler_lua(temp.path())).unwrap();
        assert!(content.contains("Profiler.stop"));
    }

    #[test]
    fn test_debug_get_frame_metrics_no_persisted() {
        let temp = tempfile::tempdir().unwrap();
        let r = req("debug.get_frame_metrics", temp.path().to_str().unwrap());
        let plan = prepare_debug(&r).unwrap();
        let res = debug_get_frame_metrics(&r, &plan).unwrap();
        assert!(res.success);
        assert!(!res.output["has_persisted_metrics"].as_bool().unwrap());
    }

    #[test]
    fn test_debug_export_diagnostics() {
        let temp = tempfile::tempdir().unwrap();
        // Create minimal project structure.
        std::fs::create_dir_all(temp.path().join(".project")).unwrap();
        std::fs::create_dir_all(temp.path().join("scripts")).unwrap();
        std::fs::write(temp.path().join("scripts").join("main.lua"), "--").unwrap();
        std::fs::write(
            temp.path().join(".project").join("project.json"),
            "{\"entry\":\"scripts/main.lua\"}",
        )
        .unwrap();

        let r = req("debug.export_diagnostics", temp.path().to_str().unwrap());
        let plan = prepare_debug(&r).unwrap();
        let res = debug_export_diagnostics(&r, &plan).unwrap();
        assert!(res.success);
        assert!(res.output["exported"].as_bool().unwrap());
        let path = res.output["path"].as_str().unwrap();
        assert!(std::path::Path::new(path).exists());
        assert_eq!(res.output["lua_files"].as_u64().unwrap(), 1);
    }

    #[test]
    fn test_debug_assert_state() {
        let temp = tempfile::tempdir().unwrap();
        let r = OperationRequest {
            request_id: "test".to_string(),
            provider_id: "taptap".to_string(),
            operation_id: "debug.assert_state".to_string(),
            project_root: None,
            arguments: json!({
                "project_root": temp.path(),
                "name": "player_alive",
                "condition": "player.hp > 0",
                "message": "player should be alive",
            }),
            timeout_ms: None,
            dry_run: false,
            plan_id: None,
            effect_digest: None,
        };
        let plan = prepare_debug(&r).unwrap();
        let res = debug_assert_state(&r, &plan).unwrap();
        assert!(res.success);
        let content = std::fs::read_to_string(profiler_lua(temp.path())).unwrap();
        assert!(content.contains("assert_player_alive"));
        assert!(content.contains("player.hp > 0"));
    }
}
