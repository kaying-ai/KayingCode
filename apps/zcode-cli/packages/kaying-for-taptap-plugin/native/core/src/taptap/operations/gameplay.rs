/// Handle `gameplay.create_behavior_tree` — write `scripts/gameplay/bt/<name>.lua`.
pub fn gameplay_create_behavior_tree(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let root_node = request
        .arguments
        .get("root")
        .cloned()
        .unwrap_or(json!({"type": "sequence", "children": []}));
    let body = format!(
        "-- bt/{name}.lua — Behavior tree\n-- Auto-generated by gameplay.create_behavior_tree.\n\nlocal BT = {{}}\n\nBT.root = {root_lua}\n\nfunction BT.tick(blackboard)\n  return BT._tickNode(BT.root, blackboard)\nend\n\nfunction BT._tickNode(node, blackboard)\n  if node.type == \"sequence\" then\n    for _, child in ipairs(node.children or {{}}) do\n      if not BT._tickNode(child, blackboard) then return false end\n    end\n    return true\n  elseif node.type == \"selector\" then\n    for _, child in ipairs(node.children or {{}}) do\n      if BT._tickNode(child, blackboard) then return true end\n    end\n    return false\n  elseif node.type == \"action\" then\n    return node.action and node.action(blackboard) or false\n  elseif node.type == \"condition\" then\n    return node.check and node.check(blackboard) or false\n  end\n  return false\nend\n\nreturn BT\n",
        root_lua = serde_json::to_string(&root_node).unwrap_or_else(|_| "{}".to_string())
    );
    let path = bt_dir(&root).join(format!("{name}.lua"));
    ensure_parent(&path)?;
    std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    info!(name = %name, "Behavior tree created");
    Ok(ok_result(
        request,
        json!({"created": true, "name": name, "path": path.to_string_lossy(), "root": root_node, "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

