/// Handle `physics.set_material` — write `.project/physics-materials/<name>.json`.
pub fn physics_set_material(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let friction = request
        .arguments
        .get("friction")
        .and_then(|v| v.as_f64())
        .unwrap_or(0.5);
    let restitution = request
        .arguments
        .get("restitution")
        .and_then(|v| v.as_f64())
        .unwrap_or(0.0);
    let material = json!({
        "name": name,
        "friction": friction,
        "restitution": restitution,
    });
    let path = physics_dir(&root).join(format!("{name}.json"));
    ensure_parent(&path)?;
    write_json_file(&path, &material).map_err(ExecuteError::Io)?;
    info!(name = %name, "Physics material written");
    Ok(ok_result(
        request,
        json!({"written": true, "name": name, "material": material, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

