//! TapTap network operations — sessions, RPC, replication, matchmaking.
//!
//! All operations generate Lua code under `scripts/systems/network.lua` or
//! `scripts/systems/network_config.lua`. Runtime-state inspection is `planned`.

use crate::model::{
    Effect, ExecuteError, OperationPlan, OperationRequest, OperationResult, PrepareError,
};
use crate::taptap::operations::helpers::{
    get_project_root, make_plan, ok_result, required_str_arg, str_arg,
};
use serde_json::json;
use std::path::{Path, PathBuf};
use std::sync::atomic::AtomicU64;
use std::time::Instant;
use tracing::info;

static PLAN_COUNTER: AtomicU64 = AtomicU64::new(0);

fn network_lua(root: &Path) -> PathBuf {
    root.join("scripts").join("systems").join("network.lua")
}

fn network_config(root: &Path) -> PathBuf {
    root.join("scripts")
        .join("systems")
        .join("network_config.lua")
}

fn ensure_parent(path: &Path) -> Result<(), ExecuteError> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(ExecuteError::Io)?;
    }
    Ok(())
}

fn ensure_network_lua(root: &Path) -> Result<(), ExecuteError> {
    let path = network_lua(root);
    if !path.exists() {
        let body = "-- network.lua — Network system facade\n-- Auto-generated by network operations.\n\nlocal Network = {}\nreturn Network\n";
        ensure_parent(&path)?;
        std::fs::write(&path, body).map_err(ExecuteError::Io)?;
    }
    Ok(())
}

fn append_to_network_lua(root: &Path, snippet: &str, marker: &str) -> Result<bool, ExecuteError> {
    let path = network_lua(root);
    ensure_network_lua(root)?;
    let mut content = std::fs::read_to_string(&path).map_err(ExecuteError::Io)?;
    if content.contains(marker) {
        Ok(false)
    } else {
        content.push_str(snippet);
        std::fs::write(&path, &content).map_err(ExecuteError::Io)?;
        Ok(true)
    }
}

// ============================================================
// network.create_session
// ============================================================

/// Handle `network.create_session` — generate session-management code.
pub fn network_create_session(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let max_players = request
        .arguments
        .get("max_players")
        .and_then(|v| v.as_u64())
        .unwrap_or(4);
    let marker = "Network.createSession";
    let snippet = format!(
        "\nfunction Network.createSession(config)\n  config = config or {{}}\n  config.maxPlayers = config.maxPlayers or {max_players}\n  -- TODO: bridge to engine networking API\n  return {{ sessionId = nil, maxPlayers = config.maxPlayers }}\nend\n"
    );
    let added = append_to_network_lua(&root, &snippet, marker)?;
    info!(max_players, added, "Create-session helper added");
    Ok(ok_result(
        request,
        json!({"added": added, "max_players": max_players, "path": network_lua(&root).to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

