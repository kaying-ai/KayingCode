/// Handle `data.create_save_schema` — write `scripts/data/save_schema.lua`.
pub fn data_create_save_schema(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let fields = request
        .arguments
        .get("fields")
        .cloned()
        .unwrap_or(json!([]));
    let fields_arr = fields.as_array().cloned().unwrap_or_default();
    let fields_lua = fields_arr
        .iter()
        .map(|f| {
            let n = f.get("name").and_then(|v| v.as_str()).unwrap_or("field");
            let t = f.get("type").and_then(|v| v.as_str()).unwrap_or("any");
            let req = if f.get("required").and_then(|v| v.as_bool()).unwrap_or(false) {
                "required"
            } else {
                "optional"
            };
            format!(
                "  {{ name = \"{n}\", type = \"{t}\", required = {req_yn} }}",
                req_yn = if req == "required" { "true" } else { "false" }
            )
        })
        .collect::<Vec<_>>()
        .join(",\n");

    let body = format!(
        "-- save_schema.lua — Save data schema for {name}\n-- Auto-generated by data.create_save_schema.\n\nlocal Schema = {{\n  name = \"{name}\",\n  version = 1,\n  fields = {{\n{fields_lua}\n  }}\n}}\n\nfunction Schema.validate(data)\n  for _, field in ipairs(Schema.fields) do\n    if field.required and data[field.name] == nil then\n      return false, \"missing required field: \" .. field.name\n    end\n  end\n  return true\nend\n\nreturn Schema\n"
    );

    let path = data_dir(&root).join("save_schema.lua");
    ensure_parent(&path)?;
    std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    info!(name = %name, path = %path.to_string_lossy(), "Save schema created");
    Ok(ok_result(
        request,
        json!({
            "created": true,
            "name": name,
            "path": path.to_string_lossy(),
            "fields": fields_arr.len(),
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

