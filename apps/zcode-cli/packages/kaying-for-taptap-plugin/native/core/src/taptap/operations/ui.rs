/// Handle `ui.bind_event` — append an event handler to a UI module.
pub fn ui_bind_event(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let module = required_str_arg(request, "module")?;
    let event = required_str_arg(request, "event")?;
    let handler = request
        .arguments
        .get("handler")
        .and_then(|v| v.as_str())
        .unwrap_or("-- TODO: implement");

    let path = ui_dir(&root).join(format!("{module}.lua"));
    let snippet = format!(
        "\nfunction M:on{event_pascal}(...)\n  {handler}\nend\n",
        event_pascal = pascal(&event)
    );

    let mut content = std::fs::read_to_string(&path).map_err(ExecuteError::Io)?;
    let func_name = format!("M:on{}", pascal(&event));
    if !content.contains(&func_name) {
        content.push_str(&snippet);
        std::fs::write(&path, &content).map_err(ExecuteError::Io)?;
    } else {
        return Ok(fail_result(
            request,
            json!({"error": format!("Event '{event}' already bound in {module}")}),
            started.elapsed().as_millis() as u64,
        ));
    }
    info!(module = %module, event = %event, "Event bound");
    Ok(ok_result(
        request,
        json!({"bound": true, "module": module, "event": event, "path": path.to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

