/// Handle `vfx.play` — generate a play function in scripts/systems/vfx.lua.
pub fn vfx_play(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let marker = format!("Vfx.play_{name}");
    let snippet = format!(
        "\nfunction Vfx.play_{name}(x, y, z)\n  -- TODO: spawn particle system from assets/vfx/{name}.particle.json at (x, y, z)\nend\n"
    );
    let added = append_to_vfx_lua(&root, &snippet, &marker)?;
    info!(name = %name, added, "Play helper added");
    Ok(ok_result(
        request,
        json!({"added": added, "name": name, "path": vfx_lua(&root).to_string_lossy(), "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

