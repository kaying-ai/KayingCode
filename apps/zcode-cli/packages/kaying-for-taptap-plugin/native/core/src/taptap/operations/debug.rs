/// Handle `debug.export_diagnostics` — export a diagnostics snapshot to
/// `.project/diagnostics/<timestamp>.json`.
pub fn debug_export_diagnostics(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();

    let now = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis())
        .unwrap_or(0);
    let stamp = format!("{now}");

    let dir = diagnostics_dir(&root);
    ensure_parent(&dir.join("x"))?;
    let out_path = dir.join(format!("{stamp}.json"));

    // Gather project metadata.
    let project_json_path = root.join(".project").join("project.json");
    let project_meta = read_json_file_opt(&project_json_path).map_err(ExecuteError::Io)?;

    // Count Lua modules and assets.
    let scripts_dir = root.join("scripts");
    let lua_count = if scripts_dir.exists() {
        count_files(&scripts_dir, "lua")
    } else {
        0
    };
    let assets_dir = root.join("assets");
    let asset_count = if assets_dir.exists() {
        count_files(&assets_dir, "")
    } else {
        0
    };
    let scenes_dir = root.join("scenes");
    let scene_count = if scenes_dir.exists() {
        count_files(&scenes_dir, "scene")
    } else {
        0
    };

    // Read modules manifest if present.
    let modules_path = root.join(".project").join("modules.json");
    let modules = read_json_file_opt(&modules_path).map_err(ExecuteError::Io)?;

    let snapshot = json!({
        "exported_at": stamp,
        "project_root": root.to_string_lossy(),
        "project": project_meta,
        "counts": {
            "lua_files": lua_count,
            "asset_files": asset_count,
            "scene_files": scene_count,
        },
        "modules_manifest": modules,
        "probe": {
            "runtime_logs_hint": "use runtime.logs to fetch stdout/stderr",
            "urhox_available": std::env::var_os("URHOX_RUNTIME").is_some(),
        },
    });

    write_json_file(&out_path, &snapshot).map_err(ExecuteError::Io)?;

    info!(path = %out_path.to_string_lossy(), "Diagnostics snapshot exported");

    Ok(ok_result(
        request,
        json!({
            "exported": true,
            "path": out_path.to_string_lossy(),
            "timestamp": stamp,
            "lua_files": lua_count,
            "asset_files": asset_count,
            "scene_files": scene_count,
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

fn count_files(dir: &Path, ext: &str) -> usize {
    let mut n = 0;
    if let Ok(entries) = std::fs::read_dir(dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                n += count_files(&path, ext);
            } else if path.is_file() {
                if ext.is_empty() || path.extension().map(|e| e == ext).unwrap_or(false) {
                    n += 1;
                }
            }
        }
    }
    n
}

