/// Handle `ui.create_canvas` — generate Canvas module under `scripts/ui/<name>.lua`.
pub fn ui_create_canvas(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let width = request
        .arguments
        .get("width")
        .and_then(|v| v.as_f64())
        .unwrap_or(1280.0);
    let height = request
        .arguments
        .get("height")
        .and_then(|v| v.as_f64())
        .unwrap_or(720.0);
    let pascal_name = pascal(&name);

    let body = format!(
        "-- {name}.lua — Canvas root module\n-- Auto-generated by ui.create_canvas.\n\nlocal {pascal_name} = {{}}\n{pascal_name}.__index = {pascal_name}\n\nfunction {pascal_name}.new()\n  local self = setmetatable({{}}, {pascal_name})\n  self.width = {width}\n  self.height = {height}\n  self.children = {{}}\n  return self\nend\n\nfunction {pascal_name}:addChild(child)\n  table.insert(self.children, child)\nend\n\nfunction {pascal_name}:draw(nvg)\n  for _, child in ipairs(self.children) do\n    if child.draw then child:draw(nvg) end\n  end\nend\n\nreturn {pascal_name}\n"
    );

    let path = ui_dir(&root).join(format!("{name}.lua"));
    if path.exists() {
        return Ok(fail_result(
            request,
            json!({"error": format!("Canvas '{name}' already exists"), "path": path.to_string_lossy()}),
            started.elapsed().as_millis() as u64,
        ));
    }
    ensure_parent(&path)?;
    std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    info!(name = %name, path = %path.to_string_lossy(), "Canvas created");
    Ok(ok_result(
        request,
        json!({"created": true, "name": name, "path": path.to_string_lossy(), "width": width, "height": height, "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

