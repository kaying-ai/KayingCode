// vfx.create_emitter
// ============================================================

/// Handle `vfx.create_emitter` — write `assets/vfx/<name>.particle.json`.
pub fn vfx_create_emitter(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let name = required_str_arg(request, "name")?;
    let path = vfx_dir(&root).join(format!("{name}.particle.json"));
    if path.exists() {
        return Ok(fail_result(
            request,
            json!({"error": format!("Emitter '{name}' already exists")}),
            started.elapsed().as_millis() as u64,
        ));
    }
    let max_particles = request
        .arguments
        .get("max_particles")
        .and_then(|v| v.as_u64())
        .unwrap_or(200);
    let lifetime = request
        .arguments
        .get("lifetime")
        .and_then(|v| v.as_f64())
        .unwrap_or(2.0);
    let emitter = json!({
        "name": name,
        "max_particles": max_particles,
        "lifetime": lifetime,
        "emission_rate": request.arguments.get("emission_rate").and_then(|v| v.as_f64()).unwrap_or(30.0),
        "shape": str_arg(request, "shape", "point"),
        "start_color": request.arguments.get("start_color").cloned().unwrap_or(json!([1.0, 1.0, 1.0, 1.0])),
        "start_size": request.arguments.get("start_size").and_then(|v| v.as_f64()).unwrap_or(0.2),
    });
    ensure_parent(&path)?;
    write_json_file(&path, &emitter).map_err(ExecuteError::Io)?;
    info!(name = %name, "Emitter created");
    Ok(ok_result(
        request,
        json!({"created": true, "name": name, "path": path.to_string_lossy(), "emitter": emitter, "project_root": root.to_string_lossy()}),
        started.elapsed().as_millis() as u64,
    ))
}

