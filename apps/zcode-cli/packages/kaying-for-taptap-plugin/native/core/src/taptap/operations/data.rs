/// Handle `data.save_game` — generate `scripts/data/save.lua` save function.
pub fn data_save_game(
    request: &OperationRequest,
    _plan: &OperationPlan,
) -> Result<OperationResult, ExecuteError> {
    let root = get_project_root(request)?;
    let started = Instant::now();
    let slot = str_arg(request, "slot", "default");

    let body = format!(
        "-- save.lua — Save game persistence (slot={slot})\n-- Auto-generated by data.save_game.\n\nlocal Save = {{}}\nlocal Schema = require \"scripts.data.save_schema\"\n\nfunction Save.write(slot, data)\n  slot = slot or \"{slot}\"\n  local ok, err = Schema.validate(data)\n  if not ok then return false, err end\n  -- TODO: bridge to engine storage API\n  return true\nend\n\nreturn Save\n"
    );

    let path = data_dir(&root).join("save.lua");
    ensure_parent(&path)?;
    std::fs::write(&path, &body).map_err(ExecuteError::Io)?;
    info!(path = %path.to_string_lossy(), "Save module written");
    Ok(ok_result(
        request,
        json!({
            "written": true,
            "path": path.to_string_lossy(),
            "slot": slot,
            "project_root": root.to_string_lossy(),
        }),
        started.elapsed().as_millis() as u64,
    ))
}

